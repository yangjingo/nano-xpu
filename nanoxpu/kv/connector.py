"""Transport contract used by stage control; this module is not a NIXL implementation."""
from typing import Protocol

from nanoxpu.kv.descriptor import KVDescriptor


class Transfer(Protocol):
    def wait_compute_visible(self, timeout: float) -> None:
        """Return only after every destination byte is visible to model computation."""
        ...

    def cancel_and_fence(self, timeout: float) -> bool:
        """True proves no current or future copy operation can access either allocation."""
        ...


class KVConnector(Protocol):
    kind: str
    version: str

    def start(self, config) -> None: ...
    def publish(self, descriptor: KVDescriptor, storage, post_event) -> None: ...
    def unpublish(self, lease_id: str) -> None: ...
    def fence_source(self, lease_id: str) -> bool: ...
    def describe(self, metadata) -> KVDescriptor: ...

    def pull(self, descriptor: KVDescriptor, storage, spans) -> Transfer:
        """Return an owned handle. On exception before returning, no DMA may remain active."""
        ...

    def ack(self, descriptor: KVDescriptor) -> None: ...
    def cancel(self, descriptor: KVDescriptor) -> None: ...
    def close(self) -> None: ...
